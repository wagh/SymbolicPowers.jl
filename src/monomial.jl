###############################################################################
#  Combinatorial engine for monomial ideals
#
#  A monomial ideal is determined by the exponent vectors of its minimal
#  monomial generators, independently of the coefficient field and of the
#  grading. Monomial ideals correspond to the up-sets of N^d that they contain;
#  sums and intersections of monomial ideals are unions and intersections of
#  these sets, so they form a distributive lattice. Everything below works on
#  exponent vectors only (no Gröbner bases, no Singular):
#
#  - x^a ∈ (x^b : b ∈ B) iff some b ≤ a componentwise;
#  - the product of (x^a : a ∈ A) and (x^b : b ∈ B) is generated by the a + b,
#    their intersection by the lcms max(a, b);
#  - an irreducible monomial ideal is (x_j^{b_j} : j ∈ T), and the irredundant
#    irreducible decomposition is unique; grouping its components by their
#    support gives a minimal primary decomposition, so the associated primes
#    are the coordinate primes P_T of those supports;
#  - for a coordinate prime P_S, I R_P ∩ R is obtained by setting the variables
#    outside S equal to 1.
#
#  Sets of exponent vectors are kept minimal and sorted by (total degree,
#  lexicographic order), so equal ideals have equal representations.
###############################################################################

const _MonoExps = Vector{Vector{Int}}

# A vector can have Int-sized entries while its total degree exceeds Int.
# Widening also suffices for every possible vector length: both length(a) and
# each nonnegative entry are at most typemax(Int), so their product fits.
const _MonoDegree = widen(Int)
_mono_degree(a::Vector{Int}) = sum(_MonoDegree, a; init=zero(_MonoDegree))

@inline function _mono_divides(a::Vector{Int}, b::Vector{Int})
  @inbounds for i in eachindex(a)
    a[i] > b[i] && return false
  end
  return true
end

# Divisibility masks, used as a prefilter. Bit k of the mask of a is set iff
# a[i] >= t for the variable i and threshold t attached to bit k. If a divides
# b, the mask of a is a subset of the mask of b. The 64 bits are spread over
# the variables occurring in the data, with thresholds evenly spaced up to the
# largest exponent of each variable (for many variables: the support).
struct _MonoMasker
  offset::Vector{Int}             # first bit of variable i
  thresholds::Vector{Vector{Int}} # increasing thresholds of variable i
end

function _MonoMasker(d::Int, sets::_MonoExps...)
  top = zeros(Int, d)
  for V in sets, v in V, i in 1:d
    top[i] = max(top[i], v[i])
  end
  active = findall(>(0), top)
  per_var = isempty(active) ? 0 : max(1, div(64, length(active)))
  offset = zeros(Int, d)
  thresholds = [Int[] for _ in 1:d]
  bit = 0
  for i in active
    bit >= 64 && break
    k = min(per_var, top[i], 64 - bit)
    thresholds[i] = unique!([Int(1 + div(widemul(j - 1, top[i]), k)) for j in 1:k])
    offset[i] = bit
    bit += length(thresholds[i])
  end
  return _MonoMasker(offset, thresholds)
end

function _mono_mask(mk::_MonoMasker, a::Vector{Int})
  m = UInt64(0)
  @inbounds for i in eachindex(mk.thresholds)
    t = mk.thresholds[i]
    c = 0
    while c < length(t) && t[c + 1] <= a[i]
      c += 1
    end
    c > 0 && (m |= ((UInt64(1) << c) - UInt64(1)) << mk.offset[i])
  end
  return m
end

_mono_masks(mk::_MonoMasker, V::_MonoExps) = UInt64[_mono_mask(mk, v) for v in V]

# The mask of column j of X.
function _mono_mask(mk::_MonoMasker, X::Matrix{Int}, j::Int)
  m = UInt64(0)
  @inbounds for i in eachindex(mk.thresholds)
    t = mk.thresholds[i]
    c = 0
    while c < length(t) && t[c + 1] <= X[i, j]
      c += 1
    end
    c > 0 && (m |= ((UInt64(1) << c) - UInt64(1)) << mk.offset[i])
  end
  return m
end

# The minimal elements of V under divisibility, without repetitions, sorted by
# (total degree, lexicographic order). A proper divisor has smaller total
# degree, so each vector is only compared with kept vectors of smaller degree.
function _mono_minimalize(V::_MonoExps)
  isempty(V) && return _MonoExps()
  deg = [_mono_degree(v) for v in V]
  p = sortperm(
    collect(eachindex(V));
    lt=(i, j) -> deg[i] < deg[j] || (deg[i] == deg[j] && isless(V[i], V[j])),
  )
  mk = _MonoMasker(length(V[1]), V)
  keep = _MonoExps()
  kmask = UInt64[]
  kdeg = _MonoDegree[]
  last = 0
  for i in p
    v = V[i]
    last != 0 && V[last] == v && continue
    last = i
    m = _mono_mask(mk, v)
    redundant = false
    @inbounds for j in eachindex(keep)
      kdeg[j] >= deg[i] && break
      (kmask[j] & ~m) == 0 || continue
      if _mono_divides(keep[j], v)
        redundant = true
        break
      end
    end
    redundant && continue
    push!(keep, v)
    push!(kmask, m)
    push!(kdeg, deg[i])
  end
  return keep
end

# Is x^a in the ideal generated by B (with masks Bm, same masker as am)?
function _mono_in(a::Vector{Int}, am::UInt64, B::_MonoExps, Bm::Vector{UInt64})
  @inbounds for j in eachindex(B)
    (Bm[j] & ~am) == 0 && _mono_divides(B[j], a) && return true
  end
  return false
end

function _mono_in(a::Vector{Int}, B::_MonoExps)
  mk = _MonoMasker(length(a), B, [a])
  return _mono_in(a, _mono_mask(mk, a), B, _mono_masks(mk, B))
end

# Containment of monomial ideals: every generator of A lies in (B).
function _mono_is_subset(A::_MonoExps, B::_MonoExps)
  isempty(A) && return true
  mk = _MonoMasker(length(A[1]), A, B)
  Bm = _mono_masks(mk, B)
  return all(a -> _mono_in(a, _mono_mask(mk, a), B, Bm), A)
end

# The number of elements of A outside the ideal (B).
function _mono_count_outside(A::_MonoExps, B::_MonoExps)
  isempty(A) && return 0
  mk = _MonoMasker(length(A[1]), A, B)
  Bm = _mono_masks(mk, B)
  return count(a -> !_mono_in(a, _mono_mask(mk, a), B, Bm), A)
end

# Generators of the product, with overflow checks on the exponents.
function _mono_product(A::_MonoExps, B::_MonoExps)
  out = _MonoExps()
  sizehint!(out, length(A) * length(B))
  for a in A, b in B
    push!(out, [Base.Checked.checked_add(a[i], b[i]) for i in eachindex(a)])
  end
  return _mono_minimalize(out)
end

# Generators of the n-th power of the ideal generated by the minimal set A in
# d variables. Minimalizing after every factor keeps the intermediate sets
# small.
function _mono_power(A::_MonoExps, n::Int, d::Int)
  n == 0 && return [zeros(Int, d)]
  isempty(A) && return _MonoExps()
  n == 1 && return A
  length(A) == 1 && return [[Base.Checked.checked_mul(n, a) for a in A[1]]]
  P = A
  for _ in 2:n
    P = _mono_product(P, A)
  end
  return P
end

# Generators of (A) ∩ (B) for minimal sets A and B. A generator of one ideal
# that lies in the other is a generator of the intersection, and all other
# lcms involving it are its multiples. For each remaining a ∈ A, the remaining
# lcms are max(a, b) = a + max(b - a, 0): x^a times the generators of the colon
# ideal (B' : x^a), which are minimalized first, as most of them are redundant.
# The colon generators and the candidates are kept in flat column storage to
# avoid allocating one vector per lcm.
function _mono_intersect(A::_MonoExps, B::_MonoExps)
  (isempty(A) || isempty(B)) && return _MonoExps()
  d = length(A[1])
  mk = _MonoMasker(d, A, B)
  Am = _mono_masks(mk, A)
  Bm = _mono_masks(mk, B)
  cand = Int[]                        # columns of length d
  restA = Int[]
  restB = Int[]
  for i in eachindex(A)
    _mono_in(A[i], Am[i], B, Bm) ? append!(cand, A[i]) : push!(restA, i)
  end
  for j in eachindex(B)
    _mono_in(B[j], Bm[j], A, Am) ? append!(cand, B[j]) : push!(restB, j)
  end
  nb = length(restB)
  C = Matrix{Int}(undef, d, nb)       # generators of (B' : x^a)
  cmask = Vector{UInt64}(undef, nb)
  cdeg = Vector{_MonoDegree}(undef, nb)
  perm = Vector{Int}(undef, nb)
  kept = Int[]
  for i in restA
    a = A[i]
    @inbounds for (jj, j) in enumerate(restB)
      b = B[j]
      s = zero(_MonoDegree)
      for k in 1:d
        v = max(b[k] - a[k], 0)
        C[k, jj] = v
        s += v
      end
      cdeg[jj] = s
      cmask[jj] = _mono_mask(mk, C, jj)
    end
    sortperm!(perm, cdeg)
    _mono_minimal_columns!(kept, C, cmask, cdeg, perm)
    @inbounds for jj in kept, k in 1:d
      push!(cand, a[k] + C[k, jj])
    end
  end
  X = reshape(cand, d, :)
  deg = vec(sum(_MonoDegree, X; dims=1))
  xmask = UInt64[_mono_mask(mk, X, j) for j in axes(X, 2)]
  _mono_minimal_columns!(kept, X, xmask, deg, sortperm(deg))
  res = _MonoExps([X[:, j] for j in kept])
  return sort!(res; by=v -> (_mono_degree(v), v))
end

# Indices of the minimal columns of X under divisibility, without repetitions,
# visiting the columns in the order `perm`, which must sort them by degree. A
# divisor has at most the same degree, and then it is equal.
function _mono_minimal_columns!(kept::Vector{Int}, X::Matrix{Int},
  mask::Vector{UInt64}, deg::Vector{_MonoDegree}, perm::Vector{Int})
  empty!(kept)
  @inbounds for j in perm
    m = mask[j]
    redundant = false
    for k in kept
      deg[k] > deg[j] && break
      (mask[k] & ~m) == 0 || continue
      if _mono_divides(X, k, j)
        redundant = true
        break
      end
    end
    redundant || push!(kept, j)
  end
  return kept
end

@inline function _mono_divides(X::Matrix{Int}, i::Int, j::Int)
  @inbounds for k in axes(X, 1)
    X[k, i] > X[k, j] && return false
  end
  return true
end

# Intersection of a nonempty list, starting with the smallest sets.
function _mono_intersect_all(L::Vector{_MonoExps})
  @req !isempty(L) "cannot intersect an empty list of ideals"
  L = sort(L; by=length)
  acc = L[1]
  for k in 2:length(L)
    acc = _mono_intersect(acc, L[k])
  end
  return acc
end

# Generators of (A) ∩ P_C^n, for the coordinate prime P_C on the variables C.
# x^a lies in P_C^n iff its C-degree s is at least n; otherwise the minimal
# multiples of x^a in P_C^n are x^(a + δ) for δ supported on C with |δ| = n - s.
function _mono_intersect_prime_power(A::_MonoExps, C::Vector{Int}, n::Int)
  out = _MonoExps()
  for a in A
    s = zero(_MonoDegree)
    for i in C
      s += a[i]
    end
    if s >= n
      push!(out, a)
    else
      _mono_distribute!(out, a, C, Int(n - s))
    end
  end
  return _mono_minimalize(out)
end

# Push a + δ for every δ ≥ 0 supported on C with |δ| = k.
function _mono_distribute!(out::_MonoExps, a::Vector{Int}, C::Vector{Int}, k::Int)
  e = copy(a)
  function rec(pos::Int, rest::Int)
    if pos == length(C)
      e[C[pos]] += rest
      push!(out, copy(e))
      e[C[pos]] -= rest
      return nothing
    end
    for t in rest:-1:0
      e[C[pos]] += t
      rec(pos + 1, rest - t)
      e[C[pos]] -= t
    end
  end
  isempty(C) || rec(1, k)
  return out
end

# Irredundant irreducible decomposition of the ideal generated by E: vectors
# b with b_j > 0 for the generators x_j^{b_j} of a component. Start with the
# zero ideal (b = 0) and add one generator x^g at a time: by distributivity
# K + (x^g) = ∩_{j ∈ supp g} (K + (x_j^{g_j})) for each component K, and each
# of these is irreducible. Components containing another one are redundant.
# An intersection of irreducible ideals none of which contains another is
# irredundant, as irreducible elements of a distributive lattice are prime.
# For a squarefree ideal the components are the minimal transversals (vertex
# covers) of the supports. The unit ideal has no components.
function _mono_irreducible_components(E::_MonoExps, d::Int)
  comps = [zeros(Int, d)]
  for g in sort(E; by=_mono_degree)
    kept = _MonoExps()
    fresh = _MonoExps()
    for b in comps
      if any(j -> b[j] > 0 && b[j] <= g[j], 1:d)
        push!(kept, b)  # x^g ∈ K
        continue
      end
      for j in 1:d
        g[j] > 0 || continue
        c = copy(b)
        c[j] = g[j]
        push!(fresh, c)
      end
    end
    # Kept components were pairwise incomparable, and a new component strictly
    # contains the old one it came from, so it cannot be contained in a kept
    # one. Only new components can be redundant.
    unique!(fresh)
    comps = kept
    for (k, c) in enumerate(fresh)
      redundant =
        any(b -> _mono_irreducible_subset(b, c), kept) ||
        any(l -> l != k && _mono_irreducible_subset(fresh[l], c), eachindex(fresh))
      redundant || push!(comps, c)
    end
  end
  return comps
end

# Is the irreducible ideal with exponents b contained in that with exponents c?
_mono_irreducible_subset(b::Vector{Int}, c::Vector{Int}) =
  all(j -> b[j] == 0 || (c[j] > 0 && c[j] <= b[j]), eachindex(b))

_mono_support(b::Vector{Int}) = BitSet(findall(>(0), b))

