# Cheap sufficient test for a monomial ideal: all given generators are terms.
_has_monomial_generators(I::MPolyIdeal) =
  all(f -> iszero(f) || _is_monomial_poly(f), gens(I))

# Exponent vectors of the minimal monomial generators of the monomial ideal I,
# cached on I (ideals built by `_mono_ideal` carry them from the start).
function _mono_exponents(I::MPolyIdeal)
  return get_attribute!(I, :symbolic_powers_monomial_exponents) do
    G = if _has_monomial_generators(I)
      filter(!iszero, gens(I))
    else
      @req is_monomial(I) "the ideal must be a monomial ideal"
      filter(!iszero, gens(groebner_basis(I; complete_reduction=true)))
    end
    _mono_minimalize(_MonoExps([exponent_vector(f, 1) for f in G]))
  end::_MonoExps
end

# The monic monomials of R with the exponent vectors in V.
function _mono_monomials(R::MPolyRing, V::_MonoExps)
  S = R isa MPolyDecRing ? forget_decoration(R) : R
  c = one(coefficient_ring(S))
  ctx = MPolyBuildCtx(S)
  mons = elem_type(R)[]
  for v in V
    push_term!(ctx, c, v)
    f = finish(ctx)
    push!(mons, R isa MPolyDecRing ? R(f) : f)
  end
  return mons
end

# The monomial ideal of R with minimal generators V (a minimal sorted set).
function _mono_ideal(R::MPolyRing, V::_MonoExps)
  isempty(V) && return _zero_ideal(R)
  I = ideal(R, _mono_monomials(R, V))
  set_attribute!(I, :symbolic_powers_monomial_exponents => V)
  return I
end

# Coordinate prime ideal on the variables in S.
_mono_prime(R::MPolyRing, S::BitSet) =
  _mono_ideal(
    R, _mono_minimalize(_MonoExps([[i == j ? 1 : 0 for i in 1:ngens(R)] for j in S]))
  )

# Supports of the associated primes of the monomial ideal I (irredundant
# irreducible decomposition). Independent of any exponent, hence cached.
function _mono_associated_supports(I::MPolyIdeal)
  return get_attribute!(I, :symbolic_powers_monomial_associated_supports) do
    d = ngens(base_ring(I))
    E = _mono_exponents(I)
    if all(e -> all(<=(1), e), E)
      # radical: the associated primes are the minimal ones
      return _mono_minimal_supports(I)
    end
    unique!([_mono_support(b) for b in _mono_irreducible_components(E, d)])
  end::Vector{BitSet}
end

# Supports of the minimal primes: the minimal transversals of the supports of
# the minimal generators (the minimal primes of the radical).
function _mono_minimal_supports(I::MPolyIdeal)
  return get_attribute!(I, :symbolic_powers_monomial_minimal_supports) do
    d = ngens(base_ring(I))
    E = unique!([Int.(e .> 0) for e in _mono_exponents(I)])
    [_mono_support(b) for b in _mono_irreducible_components(E, d)]
  end::Vector{BitSet}
end

function _mono_defining_supports(I::MPolyIdeal, use_minimal_primes::Bool)
  use_minimal_primes && return _mono_minimal_supports(I)
  A = _mono_associated_supports(I)
  return [S for S in A if !any(T -> T != S && issubset(S, T), A)]
end

# Generators of the contractions Q_{⊆S} = I R_{P_S} ∩ R for the defining
# primes P_S: the variables outside S are set to 1.
function _mono_localized_exponents(I::MPolyIdeal, use_minimal_primes::Bool)
  key = if use_minimal_primes
    :symbolic_powers_monomial_minimal_localized
  else
    :symbolic_powers_monomial_maximal_localized
  end
  return get_attribute!(I, key) do
    E = _mono_exponents(I)
    d = ngens(base_ring(I))
    [
      _mono_minimalize(_MonoExps([[i in S ? e[i] : 0 for i in 1:d] for e in E]))
      for S in _mono_defining_supports(I, use_minimal_primes)
    ]
  end::Vector{_MonoExps}
end

# Generators of I^(n) for a monomial ideal, for a nonzero proper one as the
# intersection of the n-th powers of the contractions (Cooper–Embree–Hà–
# Hoefel): (I^n) R_P ∩ R = (I R_P ∩ R)^n since both are obtained by setting
# the variables outside P equal to 1. For a squarefree ideal the contraction at
# a minimal prime P_C is P_C itself, and P_C^n is never formed.
function _mono_symbolic_power_exponents(I::MPolyIdeal, n::Int, use_minimal_primes::Bool)
  d = ngens(base_ring(I))
  E = _mono_exponents(I)
  # the zeroth power, the unit ideal and the zero ideal
  (n == 0 || E == [zeros(Int, d)]) && return [zeros(Int, d)]
  isempty(E) && return _MonoExps()
  if all(e -> all(<=(1), e), E)
    # Read the covers off the package cache of minimal primes (also used for
    # the associated primes and the symbolic polyhedron) when it is filled
    # combinatorially, i.e. when the generators are monomials.
    supports = if _has_monomial_generators(I)
      [BitSet(findfirst(>(0), e) for e in _mono_exponents(P)) for P in _minimal_primes(I)]
    else
      _mono_minimal_supports(I)
    end
    covers = sort(collect.(supports); by=length)
    acc = [zeros(Int, d)]
    for C in covers
      acc = _mono_intersect_prime_power(acc, C, n)
    end
    return acc
  end
  Qs = _mono_localized_exponents(I, use_minimal_primes)
  return _mono_intersect_all([_mono_power(Q, n, d) for Q in Qs])
end

_mono_symbolic_power(I::MPolyIdeal, n::Int, use_minimal_primes::Bool) =
  _mono_ideal(base_ring(I), _mono_symbolic_power_exponents(I, n, use_minimal_primes))

# Generators of I^n.
_mono_power_exponents(I::MPolyIdeal, n::Int) =
  _mono_power(_mono_exponents(I), n, ngens(base_ring(I)))

# Containment of monomial ideals by divisibility.
_mono_is_subset(A::MPolyIdeal, B::MPolyIdeal) =
  _mono_is_subset(_mono_exponents(A), _mono_exponents(B))

