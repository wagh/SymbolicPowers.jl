###############################################################################
#  Dimension one: points in (weighted) projective space
###############################################################################

# Throughout, R has a positive Z-grading (or is ungraded, i.e. standard
# graded), I is homogeneous and dim R/I = 1. Associated primes of homogeneous
# ideals are homogeneous, and a homogeneous prime of dimension zero contains
# every element of positive degree, so it is the irrelevant ideal m. Hence
# every minimal prime of I has dimension one (height ngens(R) - 1), every
# homogeneous prime of dimension one containing I is a minimal prime of I, and
# Ass(R/I^n) consists of the minimal primes and possibly m.

# The saturation I : m^∞, the intersection of the primary components of I
# whose primes are minimal. Cached, as containment searches compute many
# symbolic powers of the same ideal.
function _irrelevant_saturation(I::T) where {T<:MPolyIdeal}
  return get_attribute!(I, :symbolic_powers_irrelevant_saturation) do
    saturation(I, _maximal_homogeneous_ideal(base_ring(I)))
  end::T
end

# Is m an associated prime of I? Equivalently, is I not saturated?
function _irrelevant_ideal_is_associated(I::MPolyIdeal)
  return get_attribute!(I, :symbolic_powers_irrelevant_ideal_associated) do
    !(_irrelevant_saturation(I) == I)
  end::Bool
end

# Do the given generators show that I is a complete intersection, i.e. is I
# generated by at most ngens(R) - 1 = height(I) elements? (Every minimal prime
# has dimension one.) Then, in the Cohen-Macaulay local ring R_m, the
# generators form a regular sequence, each I^k / I^{k+1} is free over the
# Cohen-Macaulay ring R_m / I R_m of dimension one, so R_m / I^n R_m has
# positive depth and m is not associated to I^n. Hence Ass(R/I^n) = Min(I) and
# I^(n) = I^n for both conventions. This holds for inhomogeneous generators as
# well. Only the given generators are counted: a minimal generating set costs
# more (and compiles for seconds on its first call) than the saturation of a
# complete intersection power, which is already saturated.
_is_points_complete_intersection(I::MPolyIdeal) =
  count(!iszero, gens(I)) <= ngens(base_ring(I)) - 1

# Intersection of a nonempty list of ideals, two at a time. For powers of
# point ideals this is much faster than one call to `intersect` on the whole
# list (or than a balanced tree of intersections), see docs/src/algorithms.md.
function _fold_intersect(L::Vector{T}) where {T<:MPolyIdeal}
  @req !isempty(L) "cannot intersect an empty list of ideals"
  J = L[1]
  for i in 2:length(L)
    J = intersect(J, L[i])
  end
  return J
end

# Is P a homogeneous prime of dimension one generated by linear forms (the
# ideal of a K-rational point)? The reduced Gröbner basis of an ideal
# generated by linear forms is obtained by Gaussian elimination and consists
# of linear forms with distinct leading variables; conversely, a reduced
# Gröbner basis of linear polynomials exhibits such generators. The
# polynomials are homogeneous, so a polynomial of total degree one is a
# linear form, and such a basis of length ngens(R) - 1 generates a prime of
# dimension one.
function _is_rational_point_ideal(P::MPolyIdeal)
  G = gens(groebner_basis(P; complete_reduction=true))
  length(G) == ngens(base_ring(P)) - 1 || return false
  return all(g -> total_degree(g) == 1, G)
end

# Pairs (i, j), i < j, of variables of equal weight, in the order in which
# they are used for projections.
function _equal_weight_pairs(R::MPolyRing)
  w = _degree_weights(R)
  N = ngens(R)
  return [(i, j) for j in N:-1:2 for i in (j - 1):-1:1 if w[i] == w[j]]
end

# Candidate ideals of the points of V(J), for a homogeneous ideal J with
# dim R/J <= 1, found by projecting from the coordinate subspace
# L = {x_i = x_j = 0} to the line with coordinates (x_i : x_j). The candidates
# are pushed to `out`. Returns :ok, :fail (no conclusion: all pairs were used,
# which happens for non-standard weights if a point is not cut out by linear
# forms), or :nonrational (some minimal prime of J is not generated by linear
# forms). The ideals in the recursion contain J, so their minimal primes are
# minimal primes of J (homogeneous primes of dimension one containing J), and
# the answer :nonrational is also correct for the initial ideal.
#
# Let f be the gcd of the generators of E = J ∩ K[x_i, x_j]. If every minimal
# prime P of J is generated by linear forms, then so is P ∩ K[x_i, x_j]
# (Gaussian elimination), which is (x_i, x_j) or principal, generated by a
# linear form ℓ_P. Hence rad(E) = (h) with h the product of the distinct ℓ_P
# (or E is (x_i, x_j)-primary and f = 1), h^k ∈ E for some k, f divides h^k,
# and every irreducible factor of f is linear. So if f does not split into
# linear factors, the answer is :nonrational. Setting x_j = 1 turns the
# binary forms into univariate polynomials (only factors x_j are lost).
# Their gcd and roots are cheap.
#
# Every point outside L lies over a root of f or over (1 : 0). The fibre over
# a root (a : 1) is cut out by (J + (x_i - a x_j)) : x_j^∞, the one over
# (1 : 0) by (J + (x_j)) : x_i^∞, and the points in L by
# (J + (x_i, x_j)) : m^∞. Pieces that are not a single rational point are
# split further with the next pair of variables. This separates points with
# equal images, and repeated hyperplane sections reduce fat points (for
# instance P^2 + (ℓ) + (ℓ') = P for independent linear forms ℓ, ℓ' in a
# prime P of height two).
#
# Nothing returned here is trusted: the caller certifies the candidates.
function _project_points!(out::Vector{T}, J::T, pairs::Vector{Tuple{Int,Int}},
  d::Int) where {T<:MPolyIdeal}
  is_one(J) && return :ok
  if _is_rational_point_ideal(J)
    push!(out, J)
    return :ok
  end
  d > length(pairs) && return :fail
  R = base_ring(J)
  x = gens(R)
  i, j = pairs[d]
  others = [x[k] for k in eachindex(x) if k != i && k != j]
  E = isempty(others) ? J : eliminate(J, others)
  Kt, t = polynomial_ring(coefficient_ring(R), :t; cached=false)
  f = zero(Kt)
  for g in gens(E)
    iszero(g) && continue
    f = gcd(f, sum(c * t^e[i] for (c, e) in zip(coefficients(g), exponents(g))))
  end
  pieces = T[]
  rest = f
  for a in (degree(f) >= 1 ? roots(f) : elem_type(coefficient_ring(R))[])
    while iszero(evaluate(rest, a))
      rest = divexact(rest, t - a)
    end
    push!(pieces, saturation(J + ideal(R, [x[i] - a * x[j]]), ideal(R, [x[j]])))
  end
  degree(rest) >= 1 && return :nonrational
  push!(pieces, saturation(J + ideal(R, [x[j]]), ideal(R, [x[i]])))
  push!(pieces, saturation(J + ideal(R, [x[i], x[j]]), _maximal_homogeneous_ideal(R)))
  for F in pieces
    r = _project_points!(out, F, pairs, d + 1)
    r == :ok || return r
  end
  return :ok
end

# Is P a rational point ideal containing I? Used to certify candidates,
# whichever way they were found.
_is_rational_point_prime(P::MPolyIdeal, I::MPolyIdeal) =
  _is_rational_point_ideal(P) && is_subset(I, P)

# The largest k with J ⊆ P^k, for a nonzero homogeneous ideal J and an ideal
# P generated by linear forms (P^k contains no nonzero form of total degree
# below k, so the loop terminates).
function _point_multiplicity(J::MPolyIdeal, P::MPolyIdeal)
  k = 0
  Q = P
  while is_subset(J, Q)
    k += 1
    Q = Q * P
  end
  return k
end

# Pairs (P_i, k_i) such that the P_i are the minimal primes of I, each
# generated by linear forms, and the saturation I : m^∞ equals the
# intersection of the powers P_i^{k_i} (I is a scheme of fat K-rational
# points, away from m); `nothing` if no such list is found. The candidate
# primes come from projections. Cached on I.
#
# If P is generated by linear forms, these form a regular sequence, and after
# a linear change of coordinates P = (x_1, ..., x_h); then P^k is a monomial
# ideal whose only associated prime is P. So P^k is P-primary, i.e.
# P^(k) = P^k, over every field. The P_i have the same dimension, so they are
# pairwise incomparable, and localizing at P_i kills the components for the
# other primes: I R_{P_i} = P_i^{k_i} R_{P_i}, hence
# I^n R_{P_i} = P_i^{n k_i} R_{P_i}. For the minimal-prime convention and
# whenever m is not associated to I, the defining primes are the minimal
# primes and
#   I^(n) = ⋂_i (I^n R_{P_i} ∩ R) = ⋂_i P_i^{n k_i}.
#
# Certification. Every returned P_i is checked to be a dimension-one prime
# generated by linear forms containing I, hence a minimal prime of I, and so
# J = I : m^∞ ⊆ P_i (P_i : m^∞ = P_i). The exponent k_i is the largest k with
# J ⊆ P_i^k, so J ⊆ ⋂_i P_i^{k_i}, and the reverse inclusion is checked. Then
# no minimal prime Q is missing: J ⊆ Q would give some P_i^{k_i} ⊆ Q, so
# P_i = Q. The radical case k_i = 1 is tried first.
function _rational_point_components(I::T) where {T<:MPolyIdeal}
  return get_attribute!(
    I, :symbolic_powers_rational_point_components
  ) do
    R = base_ring(I)
    K = coefficient_ring(R)
    # Over other fields the saturation is used. Over number fields the
    # shortcut would pay off for larger examples, but the first call of
    # `roots` (or `factor`) in a session compiles for about a minute, much
    # longer than the saturations it replaces. This is a performance choice.
    (K isa QQField || K isa FinField) || return nothing
    primes = T[]
    # :fail only occurs for non-standard weights, when a point is not cut out
    # by linear forms; with all weights equal every pair of variables is used,
    # and the hyperplane sections end in the points' ideals.
    _project_points!(primes, I, _equal_weight_pairs(R), 1) == :ok ||
      return nothing
    !isempty(primes) && all(P -> _is_rational_point_prime(P, I), primes) ||
      return nothing
    J = _irrelevant_saturation(I)
    is_subset(_fold_intersect(primes), J) &&
      return [(P, 1) for P in primes]
    mults = [_point_multiplicity(J, P) for P in primes]
    all(>=(1), mults) || return nothing
    is_subset(_fold_intersect([P^k for (P, k) in zip(primes, mults)]), J) ||
      return nothing
    return collect(zip(primes, mults))
  end::Union{Nothing,Vector{Tuple{T,Int}}}
end

# The n-th symbolic power of a homogeneous ideal I with dim R/I = 1, for the
# chosen convention; the hypotheses are checked by the caller.
function _symbolic_power_points(I::MPolyIdeal, n::Int, use_minimal_primes::Bool)
  # If m is associated to I, it is the unique maximal associated prime of I,
  # and I^n R_m ∩ R = I^n since every associated prime of the homogeneous
  # ideal I^n lies in m. Otherwise (or for the minimal-prime convention) only
  # the m-primary component of I^n has to be removed.
  if !use_minimal_primes && _irrelevant_ideal_is_associated(I)
    return I^n
  end
  # complete intersections (for instance collinear points): I^n is unmixed
  _is_points_complete_intersection(I) && return I^n
  # Schemes of (fat) K-rational points, for instance all point configurations
  # with rational coordinates: intersect powers of the point ideals. This is
  # much faster than saturating I^n, see docs/src/algorithms.md. Other
  # primes would need a decomposition, P^n need not be primary, and even for
  # complete intersection primes the intersection is not reliably faster (it
  # is much slower for the Fermat configuration).
  comps = _rational_point_components(I)
  comps === nothing || return _fold_intersect([P^(n * k) for (P, k) in comps])
  return saturation(I^n, _maximal_homogeneous_ideal(base_ring(I)))
end
