# An independent bounded oracle: exponent arithmetic and monomial colons.
# No package helpers or primary decomposition are used for expected membership.
function oracle_minimal(E)
  V = unique(E)
  return [a for a in V if !any(b -> b != a && all(b .<= a), V)]
end

function oracle_associated_supports(E)
  d = length(first(E))
  bounds = [maximum(e[i] for e in E) for i in 1:d]
  supports = Vector{Int}[]
  for witness in Iterators.product((0:b for b in bounds)...)
    colon = oracle_minimal([max.(e .- collect(witness), 0) for e in E])
    all(e -> sum(e) == 1, colon) || continue
    push!(supports, sort([findfirst(==(1), e) for e in colon]))
  end
  return unique(supports)
end

function oracle_power(E, n)
  d = length(first(E))
  out = [zeros(Int, d)]
  for _ in 1:n
    out = oracle_minimal([a .+ b for a in out for b in E])
  end
  return out
end

@testset "independent monomial localization oracle" begin
  R, (x, y, z) = polynomial_ring(QQ, [:x, :y, :z])
  examples = [
    [[1, 1, 0], [1, 0, 1], [0, 1, 1]],
    [[2, 0, 0], [1, 1, 0]],
    [[2, 0, 0], [0, 2, 0]],
    [[1, 1, 0], [1, 0, 1]],
    [[3, 0, 0], [2, 2, 0], [1, 0, 3], [0, 4, 0], [0, 2, 1]],
    [[2, 1, 0], [0, 2, 1], [1, 0, 2]],
  ]
  # All nonzero ideals generated by a subset of these four small monomials.
  pool = [[2, 0, 0], [1, 1, 0], [0, 2, 0], [0, 1, 1]]
  for mask in 1:15
    push!(examples, [pool[i] for i in 1:4 if !iszero(mask & (1 << (i - 1)))])
  end
  for E in examples
    I = ideal(R, [prod(gens(R)[i]^e[i] for i in 1:3) for e in E])
    primes = oracle_associated_supports(E)
    @test !isempty(primes)
    @test associated_prime_heights(I) == sort(unique(length.(primes)))
    for minimal_only in (false, true), n in 1:3
      targets = if minimal_only
        [p for p in primes if !any(q -> q != p && issubset(q, p), primes)]
      else
        primes
      end
      local_powers = [
        oracle_power([[i in p ? e[i] : 0 for i in 1:3] for e in E], n)
        for p in targets
      ]
      S = symbolic_power(I, n; method=:monomial, use_minimal_primes=minimal_only)
      D = symbolic_power(I, n; method=:primary, use_minimal_primes=minimal_only)
      @test S == D
      # Every lattice exponent in the test box is checked against localization.
      for a in Iterators.product(0:4, 0:4, 0:4)
        expected = all(F -> any(e -> all(e .<= collect(a)), F), local_powers)
        m = prod(gens(R)[i]^a[i] for i in 1:3)
        @test (m in S) == expected
      end
    end
  end
end
